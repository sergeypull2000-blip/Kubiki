import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { spawn } from "node:child_process";

const target = resolve("db/migrations/001_better_auth_1_7_1.generated.sql");
const tempDirectory = await mkdtemp(join(tmpdir(), "kubiki-better-auth-"));
const generated = join(tempDirectory, "generated.sql");
const cli = resolve("node_modules/auth/dist/index.mjs");

try {
  await new Promise((resolvePromise, reject) => {
    const child = spawn(
      process.execPath,
      [cli, "generate", "--config", "server/auth.js", "--output", generated, "--yes"],
      {
        cwd: resolve("."),
        env: { ...process.env, BETTER_AUTH_SCHEMA_GENERATION: "1" },
        stdio: "inherit",
      },
    );
    child.once("error", reject);
    child.once("exit", (code) =>
      code === 0 ? resolvePromise() : reject(new Error(`auth CLI exited ${code}`)),
    );
  });

  const sql = (await readFile(generated, "utf8")).replaceAll("\r\n", "\n").trimEnd() + "\n";
  const preamble = `-- Generated by auth@1.7.1 from server/auth.js for better-auth@1.7.1.\n-- Regenerate with: npm run db:generate-auth-schema\n-- The schema/search_path preamble is Kubiki-owned; all DDL below it is CLI output.\ncreate schema if not exists auth;\nset search_path = auth, pg_catalog;\n\n`;
  const next = preamble + sql;
  if (process.argv.includes("--check")) {
    const current = (await readFile(target, "utf8")).replaceAll("\r\n", "\n");
    if (current !== next) {
      throw new Error("Better Auth schema artifact is not reproducible");
    }
  } else {
    await writeFile(target, next, "utf8");
  }
} finally {
  await rm(tempDirectory, { recursive: true, force: true });
}
