export function normalizeRoleText(value) {
  return String(value ?? "").normalize("NFKC").toLocaleLowerCase("ru-RU").replace(/ё/g, "е").replace(/[^\p{L}\p{N}]+/gu, " ").trim().replace(/\s+/g, " ");
}

export function isStudioRole(role) {
  const normalized = normalizeRoleText(role);
  if (!normalized) return false;
  return STUDIO_ROLES.some((canonical) => normalizeRoleText(canonical) === normalized);
}

function fuzzyRoleMatches(query) {
  const tokens = query.split(" ").filter((token) => token.length >= 3);
  if (!tokens.length) return [];
  const scored = [];
  for (const role of STUDIO_ROLES) {
    const roleText = normalizeRoleText(role);
    const keywords = TASK_ROLE_MAP.find((entry) => entry.role === role)?.keywords || [];
    const aliases = [roleText, ...roleText.split(" "), ...keywords];
    const score = tokens.reduce((sum, token) => sum + (aliases.some((alias) => alias === token || alias.startsWith(token) || token.startsWith(alias) || roleText.includes(token)) ? 1 : 0), 0);
    if (score > 0) scored.push({ role, score });
  }
  return scored.sort((a, b) => b.score - a.score || STUDIO_ROLES.indexOf(a.role) - STUDIO_ROLES.indexOf(b.role)).map((entry) => entry.role);
}

/* Сопоставляет название задачи с ролями студии.
   Возвращает упорядоченный список ролей: сначала точные совпадения
   (в порядке приоритета), затем нечёткий резерв, затем сквозные роли. */
export function matchTaskToRoles(taskName, { includeCrossCutting = true } = {}) {
  const query = normalizeRoleText(taskName);
  const roles = [];
  if (query) {
    for (const role of STUDIO_ROLES) {
      const roleText = normalizeRoleText(role);
      if (query === roleText || query.includes(roleText)) roles.push(role);
    }
    for (const entry of TASK_ROLE_MAP) {
      if (!roles.includes(entry.role) && entry.keywords.some((keyword) => query.includes(keyword))) roles.push(entry.role);
    }
    if (!roles.length) roles.push(...fuzzyRoleMatches(query));
  }
  if (includeCrossCutting) for (const role of CROSS_CUTTING_ROLES) if (!roles.includes(role)) roles.push(role);
  return roles;
}

